#!/usr/bin/env python3
"""
Test if autoparser-generated selectors actually work by running the pipeline.

Usage:
    python test_generated_selectors.py --source-id <source_id>
"""
import sys
import json
import argparse
from pathlib import Path

# Add backend directory to path
backend_dir = Path(__file__).parent.parent
sys.path.insert(0, str(backend_dir))

from utils.html_autoparser import parse_html_autoparser
from utils.pipeline import run_source_pipeline
import requests


SOURCES_FILE = backend_dir / "sources.json"


def test_generated_selectors(source_id: str):
    """Test if autoparser-generated selectors work."""
    # Load source
    with open(SOURCES_FILE, 'r') as f:
        sources = json.load(f)
    
    source = next((s for s in sources if s.get('id') == source_id), None)
    if not source:
        print(f"Source '{source_id}' not found")
        return 1
    
    url = source.get('url', '')
    firm_name = source.get('firm_name', '')
    
    print(f"\n{'='*70}")
    print(f"Testing Generated Selectors: {firm_name} ({source_id})")
    print(f"URL: {url}")
    print(f"{'='*70}\n")
    
    # Step 1: Run autoparser
    print("Step 1: Running autoparser...")
    try:
        response = requests.get(url, timeout=15, headers={
            'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36'
        }, allow_redirects=True)
        
        if response.status_code != 200:
            print(f"✗ HTTP {response.status_code}")
            return 1
        
        autoparser_result = parse_html_autoparser(url, response.text, response.url)
        
        if not autoparser_result.get('selectors_json'):
            print("✗ No selectors generated by autoparser")
            return 1
        
        selectors = autoparser_result['selectors_json']
        detail_fetch = autoparser_result.get('detail_fetch_patch')
        
        print(f"✓ Selectors generated:")
        for key, value in selectors.items():
            print(f"  {key}: {value}")
        
        if detail_fetch:
            print(f"\n⚠ Detail fetch required:")
            for key, value in detail_fetch.items():
                print(f"  {key}: {value}")
        
    except Exception as e:
        print(f"✗ Autoparser failed: {e}")
        return 1
    
    # Step 2: Test with pipeline
    print(f"\nStep 2: Testing with pipeline...")
    try:
        test_source = source.copy()
        test_source['selectors_json'] = selectors
        if detail_fetch:
            test_source['detail_fetch'] = detail_fetch
        
        pipeline_result = run_source_pipeline(test_source)
        kept_events = pipeline_result.get('kept_events', [])
        run_stats = pipeline_result.get('run_stats', {})
        
        print(f"\n✓ Pipeline Results:")
        print(f"  Events found: {len(kept_events)}")
        print(f"  Raw items: {run_stats.get('raw_count', 0)}")
        print(f"  Dated events: {run_stats.get('dated_count', 0)}")
        print(f"  Future events: {run_stats.get('future_count', 0)}")
        print(f"  Dated ratio: {run_stats.get('dated_ratio', 0.0):.1%}")
        
        if kept_events:
            print(f"\n  Sample events (first 3):")
            for i, event in enumerate(kept_events[:3], 1):
                print(f"    {i}. {event.get('event_name', 'N/A')[:60]}")
                print(f"       Date: {event.get('date_time', 'No date')}")
                print(f"       URL: {event.get('link', 'N/A')[:60]}")
        
        if len(kept_events) >= 3:
            print(f"\n✓ SUCCESS: Selectors work! Found {len(kept_events)} events")
            return 0
        elif len(kept_events) > 0:
            print(f"\n⚠ PARTIAL: Only {len(kept_events)} events (need 3+)")
            return 0
        else:
            print(f"\n✗ FAILED: No events extracted")
            return 1
            
    except Exception as e:
        print(f"✗ Pipeline failed: {e}")
        import traceback
        traceback.print_exc()
        return 1


def main():
    parser = argparse.ArgumentParser(description='Test generated selectors')
    parser.add_argument('--source-id', required=True, help='Source ID to test')
    
    args = parser.parse_args()
    
    return test_generated_selectors(args.source_id)


if __name__ == '__main__':
    sys.exit(main())
